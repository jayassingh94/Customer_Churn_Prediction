import pandas as pd
df= pd.read_csv(r"C:\Users\Jaya Singh\talkback_podcast\lib\core\constants\customer_churn.csv")
print(df.head())
print(df.info())
print(df.shape)
print(df["Tenure"])
print(df["Tenure"].head())
print(df["Tenure"].min())
print(df["Tenure"].max())
print(df["Tenure"].mean())
print(df[df["Tenure"] >50])
print(df.loc[100])
print(df["Tenure"].loc[100])
print(df["Tenure"].iloc[99])
print(df.iloc[99])
print(df.isnull().sum())
df["Tenure"] = df["Tenure"].fillna(df["Tenure"].median())
df["MonthlyCharges"]= df["MonthlyCharges"].fillna(df["MonthlyCharges"].median())
print(df.isnull().sum())
print(df.describe())
print(df.groupby("Churn")[["Tenure", "MonthlyCharges", "Age"]].mean())
df["Churn_num"] = df["Churn"].map({"Yes":1, "No":0})
print(df[["Tenure", "MonthlyCharges", "Age","Churn_num"]].corr()["Churn_num"].sort_values(ascending= False))
print(df["Contract"].value_counts())
df_encoded = pd.get_dummies(df,columns= ["Contract","PaymentMethod","InternetService"], drop_first= True)
print(df_encoded.corr(numeric_only = True)["Churn_num"].sort_values(ascending= False))
print(df.groupby("Contract")["Churn_num"].mean().sort_values(ascending= False))
print(df.groupby("PaymentMethod")["Churn_num"].mean().sort_values(ascending= False))
x= df_encoded.drop(["Churn", "Churn_num"], axis= 1)
y= df_encoded["Churn_num"]
from sklearn.model_selection import train_test_split
x_train, x_test, y_train, y_test= train_test_split(x,y, test_size= 0.2, random_state= 42)
from sklearn.linear_model import LogisticRegression
from sklearn.ensemble import RandomForestClassifier
logreg= LogisticRegression(max_iter= 1000, class_weight= "balanced")
logreg.fit(x_train, y_train)
logreg_pred= logreg.predict(x_test)
rf= RandomForestClassifier(random_state= 42, class_weight= "balanced")
rf.fit(x_train, y_train)
rf_pred = rf.predict(x_test)
print("--Logistic Regression--")
from sklearn.metrics import classification_report
print(classification_report(y_test,logreg_pred))
print("--RandomForest--")
print(classification_report(y_test,rf_pred))
from sklearn.model_selection import cross_val_score
logreg_cv= cross_val_score (logreg, x, y, cv= 5, scoring= "recall")
rf_cv= cross_val_score(rf,x,y, cv=5, scoring= "recall")
print("Logistic Regression recall (5-fold):", logreg_cv.mean().round(3))
print("Random Forest Recall (5-fold):", rf_cv.mean(). round(3))
importances= pd.Series(rf.feature_importances_,index= x.columns)
print(importances.sort_values(ascending= False).head(10))
